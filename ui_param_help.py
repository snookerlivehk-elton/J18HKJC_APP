# --- 平滑 ---
def smooth_c(entity: str) -> str:
    return (
        f"{entity}分數的貝葉斯平滑常數（虛擬平均出賽次數）。"
        f"調高→樣本少時更往平均拉、極端分較少；調低→更信小樣本真實表現、噪音較大。"
    )


